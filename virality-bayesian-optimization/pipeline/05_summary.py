"""
05_summary.py - write RESULTS.md and results/summary.json from the stage
pickles. These are the only numbers the README / blog should quote.
"""
import os, json, pickle
import numpy as np
from common import HERE, TD_SIMS

FILES = {1: 'bo_results.pkl', 2: 'bo_strong_results.pkl', 3: 'bo_freenode_results.pkl', 4: 'bo_constrained_results.pkl'}
S = {i: pickle.load(open(os.path.join(HERE, f), 'rb')) for i, f in FILES.items()}
for k in ('K', 'IC_P', 'MC', 'FINAL_SIMS'):
    assert len({S[i][k] for i in S}) == 1, 'stages disagree on ' + k
assert not any(S[i]['QUICK'] for i in S), 'refusing to summarise QUICK smoke-test pickles'
B = S[1]['baselines']; TD = B['td_final']
pct = lambda a: 100 * (a - TD) / TD

def f(x, d=1): return ('%.' + str(d) + 'f') % x

lines = ['# Results (generated by `pipeline/05_summary.py` - do not edit by hand)', '',
         'Objective, all stages: k=%d seeds, IC p=%s, %d sims per evaluation; winners re-evaluated with %d fresh sims. '
         'Graph: Higgs retweet WCC, %s nodes / %s edges, edges oriented retweeted -> retweeter.'
         % (S[1]['K'], S[1]['IC_P'], S[1]['MC'], S[1]['FINAL_SIMS'], f'{S[1]["graph_nodes"]:,}', f'{S[1]["graph_edges"]:,}'),
         '', 'Shared baselines: top-degree **%s** (%d sims; 30x150-sim reps: %s ± %s); random seeds %s ± %s.'
         % (f(TD), TD_SIMS, f(B['td_mean']), f(B['td_std']), f(B['rand_mean']), f(B['rand_std'])), '',
         '## BO vs random search vs top-degree', '',
         '| Stage | Space | Evals/run | Runs | BO mean ± sd | BO vs top-degree | BO runs > top-degree | Random search mean ± sd | Best BO set: shared w/ top-degree | Best set vs top-degree (Welch, set-level) |',
         '|---|---|---|---|---|---|---|---|---|---|']
summary = dict(objective=dict(K=S[1]['K'], IC_P=S[1]['IC_P'], MC=S[1]['MC'], FINAL_SIMS=S[1]['FINAL_SIMS']),
               baselines=dict(top_degree=TD, top_degree_reps_mean=B['td_mean'], top_degree_reps_std=B['td_std'],
                              random_mean=B['rand_mean'], random_std=B['rand_std']), stages={})
for i, R in S.items():
    b, r, t = R['bo_summary'], R['rs_summary'], R['setlevel']
    lines.append('| %d | %s | %d | %d | %s ± %s | %+.2f%% | %d/%d | %s ± %s | %d/%d | %s vs %s, t=%.2f, p=%.2g |' % (
        i, R['label'], R['bo_curves'].shape[1], b['n_runs'], f(b['mean']), f(b['std']), pct(b['mean']),
        b['n_beat_td'], b['n_runs'], f(r['mean']), f(r['std']), R['shared'], R['K'],
        f(t['mean']), f(B['td_mean']), t['t'], t['p']))
    summary['stages'][i] = dict(label=R['label'], dim=R['dim'], evals_per_run=int(R['bo_curves'].shape[1]),
                                bo=b, random_search=r, bo_finals=list(map(float, R['bo_finals'])),
                                rs_finals=list(map(float, R['rs_finals'])), best_final=float(R['best_final']),
                                shared_with_top_degree=int(R['shared']), setlevel=t,
                                overlap_top_degree=float(R['ov_td']), overlap_best_bo=float(R['ov_bo']))

R2, R4 = S[2], S[4]
lines += ['', '## Stage-specific controls', '',
          '- **Heuristics (stage 1):** ' + ', '.join('%s %s' % (k, f(v)) for k, v in S[1]['heur'].items()) + '.',
          '- **CELF (stage 2):** lazy greedy on 200 fixed live-edge snapshots over the top-3000 out-degree pool; '
          'snapshot estimate %s, fresh %d-sim %s (%+.2f%% vs top-degree; set-level t=%.2f, p=%.2g); shares %d/%d seeds with top-degree.'
          % (f(R2['celf_saa']), R2['FINAL_SIMS'], f(R2['celf_final']), pct(R2['celf_final']),
             R2['celf_test']['t'], R2['celf_test']['p'], R2['celf_shared'], R2['K']),
          '- **Decoder-only (stage 4):** z=0 (no BO bias), diversity weight swept on an 11-point grid; best fresh %s '
          '(%+.2f%% vs top-degree; set-level p=%.2g). BO runs above decoder-only: %d/%d.'
          % (f(R4['dec_final']), pct(R4['dec_final']), R4['dec_test']['p'],
             int((R4['bo_finals'] > R4['dec_final']).sum()), R4['bo_summary']['n_runs']),
          '- **Stage 3 pool:** %d embedded nodes; %d/%d top-degree seeds are inside it.'
          % (S[3]['pool'], S[3]['td_in_pool'], S[3]['K']),
          '', '## How to read the p-values', '',
          'The set-level Welch test compares Monte Carlo estimates of two *fixed* seed sets. It supports '
          '"this particular seed set spreads more/less than top-degree", not "BO beats top-degree". '
          'Method-level evidence is the run-level columns: mean ± sd across independent BO runs and how many runs beat top-degree.']
summary['controls'] = dict(celf_final=float(R2['celf_final']), celf_snapshot=float(R2['celf_saa']),
                           decoder_only_final=float(R4['dec_final']))

os.makedirs(os.path.join(HERE, '..', 'results'), exist_ok=True)
open(os.path.join(HERE, '..', 'RESULTS.md'), 'w').write('\n'.join(lines) + '\n')
json.dump(summary, open(os.path.join(HERE, '..', 'results', 'summary.json'), 'w'), indent=2, default=float)
print('\n'.join(lines))
