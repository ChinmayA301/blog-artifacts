"""Stage 6 figure + summary table: known vs unknown dynamics, one-shot vs multi-round.
Reads ../pipeline/unknown_dynamics.pkl (or _quick with QUICK=1); writes
figures/unknown_dynamics.png, ../results/unknown_dynamics.json and ../RESULTS_unknown_dynamics.md."""
import json
from style import *

QUICK = os.environ.get('QUICK') == '1'
D = pickle.load(open(os.path.join(PIPE, 'unknown_dynamics%s.pkl' % ('_quick' if QUICK else '')), 'rb'))
R = D['results']; T = D['T']
POL = ['oracle', 'prior-greedy', 'CUCB', 'Thompson', 'BO']
COL = {'oracle': PURPLE, 'prior-greedy': MUTE, 'CUCB': RED, 'Thompson': ORANGE, 'BO': BLUE}
LAB = {'oracle': 'Greedy, true model (known dynamics)', 'prior-greedy': 'Greedy, aggregate calibration only',
       'CUCB': 'CUCB (learns per-account rates)', 'Thompson': 'Thompson sampling (learns per-account rates)',
       'BO': 'BO over centrality blend, 1 cascade/eval'}
TITLE = {'W1_homogeneous': 'W1: every account equally transmissible',
         'W3_mild_heterogeneity': 'W3: mild per-account differences',
         'W2_heterogeneous': 'W2: per-account rates as in the data'}

summary = dict(T=T, N_RUNS=D['N_RUNS'], K=D['K'], F=D['F'], C=D['C'], ALPHA=D['ALPHA'], worlds={})
fig, axes = plt.subplots(1, len(R), figsize=(5.2 * len(R), 5.2), sharey=False)
for ax, (w, W) in zip(np.atleast_1d(axes), R.items()):
    td = W['policies']['top-degree']['rewards']                       # runs x T
    td_ref = W['ref']['top-degree']
    S = dict(ref={k: float(v) for k, v in W['ref'].items()}, c_pool_pct=[float(x) for x in np.percentile(W['c'], [10, 50, 90])],
             oracle_vs_td_pct=float(100 * (W['ref']['oracle'] / td_ref - 1)), policies={})
    t = np.arange(1, T + 1)
    for p in POL:
        r = W['policies'][p]['rewards']
        cum = np.cumsum(r, 1) / np.cumsum(td, 1)                      # matched rounds, same run index
        rel = 100 * (cum - 1)
        ax.plot(t, rel.mean(0), color=COL[p], lw=2, label=LAB[p])
        if r.shape[0] > 1:
            ax.fill_between(t, rel.min(0), rel.max(0), color=COL[p], alpha=0.12, lw=0)
        below = np.where(rel.mean(0) < 0)[0]
        S['policies'][p] = dict(
            one_shot_round1_pct=float(100 * (r[:, 0].mean() / td_ref - 1)),
            first10_pct=float(100 * (r[:, :10].mean() / td_ref - 1)),
            all_rounds_pct=float(100 * (r.mean() / td_ref - 1)),
            last10_pct=float(100 * (r[:, -10:].mean() / td_ref - 1)),
            final_set_pct=float(100 * (W['policies'][p]['final_expected'].mean() / td_ref - 1)),
            cumulative_breakeven_round=(None if len(below) and below[-1] == T - 1 else
                                        int(below[-1] + 2) if len(below) else 1))
    ax.axhline(0, color=GREEN, ls='--', lw=1.4, label='Top-degree')
    ax.set_title(TITLE.get(w, w), loc='left', fontsize=11)
    ax.set_xlabel('Campaign round (one real cascade each)')
    ax.text(0.02, 0.03, 'per-account rate, top-%d pool: p10 %.2f, median %.2f, p90 %.2f' % (D['POOL'], *S['c_pool_pct']),
            transform=ax.transAxes, fontsize=7.5, color='#555')
    clean(ax)
    summary['worlds'][w] = S
np.atleast_1d(axes)[0].set_ylabel('Cumulative reach vs top-degree (%)')
h, l = np.atleast_1d(axes)[0].get_legend_handles_labels()
fig.legend(h, l, loc='lower center', ncol=3, fontsize=9, frameon=False, bbox_to_anchor=(0.5, 0.06))
fig.suptitle('Unknown dynamics, costly feedback: learning per-account rates pays only when accounts differ',
             x=0.01, ha='left', fontsize=13)
fig.text(0.01, 0.01, 'Higgs follower graph, weighted cascade (floor %d, c=%.3f), k=%d. Lines = mean over %d runs of cumulative reach '
         'divided by top-degree\'s over the same rounds; bands = min-max across runs.' % (D['F'], D['C'], D['K'], D['N_RUNS']),
         fontsize=8.5, color='#777')
fig.subplots_adjust(left=0.06, right=0.99, top=0.85, bottom=0.27, wspace=0.22)
fname = ('unknown_dynamics%s.png' % ('_quick' if QUICK else '')).replace('.png', TAG + '.png')
plt.savefig(os.path.join(OUT, fname), bbox_inches='tight'); plt.close(); print('wrote', fname)

RES = os.path.join(HERE, '..', 'results'); os.makedirs(RES, exist_ok=True)
json.dump(summary, open(os.path.join(RES, 'unknown_dynamics%s.json' % ('_quick' if QUICK else '')), 'w'), indent=1)

# markdown table
L = ['# Stage 6: unknown dynamics, costly feedback (generated by charts/06_unknown_dynamics_charts.py)', '',
     'Higgs follower graph, weighted cascade p_uv = c_u / max(followees(v), %d), c = %.3f, k = %d, '
     '%d rounds x %d runs. Every percentage is relative to top-degree in the same world. '
     'Fixed policies (oracle, prior-greedy, top-degree) choose the same set every round.' % (D['F'], D['C'], D['K'], T, D['N_RUNS']), '']
for w, S in summary['worlds'].items():
    L += ['## %s' % TITLE.get(w, w), '',
          'Top-degree expected reach %.0f; oracle %+.1f%%; snapshot CELF on the true model %+.1f%% '
          '(checks the fast greedy oracle).' % (S['ref']['top-degree'], S['oracle_vs_td_pct'],
                                                100 * (S['ref']['celf'] / S['ref']['top-degree'] - 1)), '',
          '| Policy | Round 1 (one-shot) | Rounds 1-10 | All %d rounds | Last 10 | Final seed set | Cumulative break-even |' % T,
          '|---|---|---|---|---|---|---|']
    for p, v in S['policies'].items():
        be = v['cumulative_breakeven_round']
        L.append('| %s | %+.1f%% | %+.1f%% | %+.1f%% | %+.1f%% | %+.1f%% | %s |' % (
            p, v['one_shot_round1_pct'], v['first10_pct'], v['all_rounds_pct'], v['last10_pct'], v['final_set_pct'],
            'never' if be is None else 'round %d' % be))
    L.append('')
open(os.path.join(HERE, '..', 'RESULTS_unknown_dynamics%s.md' % ('_quick' if QUICK else '')), 'w').write('\n'.join(L))
print('\n'.join(L))

# ---- dose-response: how much per-account heterogeneity before learning pays? ----
GP = os.path.join(PIPE, 'unknown_dynamics_gamma.pkl')
if os.path.exists(GP) and not QUICK:
    G = pickle.load(open(GP, 'rb'))['results']
    pts = [(0.0, R['W1_homogeneous'])] + [(float(k.split('_')[1]), v) for k, v in G.items()] + [(1.0, R['W2_heterogeneous'])]
    pts.sort(key=lambda x: x[0])
    rows = []
    for gm, W in pts:
        td = W['ref']['top-degree']; c = W['policies']['CUCB']['rewards']
        rows.append(dict(gamma=gm, oracle_pct=100 * (W['ref']['oracle'] / td - 1),
                         cucb_first10_pct=100 * (c[:, :10].mean() / td - 1),
                         cucb_all50_pct=100 * (c.mean() / td - 1),
                         cucb_final_pct=100 * (W['policies']['CUCB']['final_expected'].mean() / td - 1),
                         c_pool_p10_p90=[float(x) for x in np.percentile(W['c'], [10, 90])], n_runs=int(c.shape[0])))
    fig, ax = plt.subplots(figsize=(9, 5.4))
    x = [r['gamma'] for r in rows]
    ax.plot(x, [r['oracle_pct'] for r in rows], 'o-', color=PURPLE, lw=2, label='Greedy with the true model (headroom)')
    ax.plot(x, [r['cucb_all50_pct'] for r in rows], 's-', color=RED, lw=2, label='CUCB, average over all %d rounds' % T)
    ax.plot(x, [r['cucb_first10_pct'] for r in rows], 's--', color=RED, alpha=0.5, lw=1.5, label='CUCB, first 10 rounds')
    ax.axhline(0, color=GREEN, ls='--', lw=1.4, label='Top-degree')
    for r in rows:
        ax.annotate('p10-p90 rate\n%.2f-%.2f' % tuple(r['c_pool_p10_p90']), (r['gamma'], r['oracle_pct']),
                    textcoords='offset points', xytext=(0, 10), ha='center', fontsize=7.5, color='#555')
    ax.set_xlabel('Per-account heterogeneity  (0 = all accounts equal, 1 = rates as estimated from the data)')
    ax.set_ylabel('Reach vs top-degree (%)')
    ax.set_title('Learning pays once the headroom over top-degree exceeds the cost of exploring', loc='left')
    ax.legend(loc='upper left', fontsize=9, frameon=True); clean(ax)
    ax.set_ylim(top=max(r['oracle_pct'] for r in rows) + 4)
    caption(ax, 'c_u = s * c * (c_u^data / c)^gamma, rescaled to the same aggregate transmissibility.\nHiggs follower graph, weighted cascade '
                'floor %d, k=%d; gamma 0 and 1: %d runs, 0.25 and 0.5: %d runs.' % (D['F'], D['K'], D['N_RUNS'], rows[1]['n_runs']), y=-0.17)
    save('unknown_dynamics_dose_response.png')
    summary['dose_response'] = rows
    json.dump(summary, open(os.path.join(RES, 'unknown_dynamics.json'), 'w'), indent=1)
    L = ['## Dose-response: how heterogeneous must accounts be?', '',
         'c_u = s * c * (c_u^W2 / c)^gamma, rescaled to W2\'s aggregate. gamma 0 = W1, gamma 1 = W2. CUCB only.', '',
         '| gamma | Headroom (oracle vs top-degree) | CUCB rounds 1-10 | CUCB all %d rounds | CUCB final set |' % T, '|---|---|---|---|---|']
    L += ['| %g | %+.1f%% | %+.1f%% | %+.1f%% | %+.1f%% |' % (r['gamma'], r['oracle_pct'], r['cucb_first10_pct'],
                                                            r['cucb_all50_pct'], r['cucb_final_pct']) for r in rows]
    open(os.path.join(HERE, '..', 'RESULTS_unknown_dynamics.md'), 'a').write('\n' + '\n'.join(L) + '\n')
    print('\n'.join(L))
